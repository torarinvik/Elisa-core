package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"path/filepath"
	"strconv"
	"strings"
)

const generatedLineBudget = 570

type generatedPart struct {
	name string
	data []byte
}

// splitGenerated keeps complete declarations together. The generated copier has
// no declaration comments; its only comment is the generated-file header.
func splitGenerated(source []byte) ([]generatedPart, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "syntax_snapshot_gen.go", source, 0)
	if err != nil {
		return nil, err
	}
	var declarations []ast.Decl
	for _, decl := range file.Decls {
		if group, ok := decl.(*ast.GenDecl); ok && group.Tok == token.IMPORT {
			continue
		}
		declarations = append(declarations, decl)
	}
	imports := map[string]string{}
	for _, spec := range file.Imports {
		path, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			return nil, err
		}
		name := filepath.Base(path)
		if spec.Name != nil {
			name = spec.Name.Name
		}
		imports[name] = path
	}
	var groups [][]ast.Decl
	var group []ast.Decl
	lines := 0
	for _, decl := range declarations {
		start, end := fset.Position(decl.Pos()).Line, fset.Position(decl.End()).Line
		size := end - start + 2
		if size > generatedLineBudget {
			return nil, fmt.Errorf("generated declaration at line %d needs %d lines", start, size)
		}
		if len(group) > 0 && lines+size > generatedLineBudget {
			groups = append(groups, group)
			group, lines = nil, 0
		}
		group = append(group, decl)
		lines += size
	}
	if len(group) > 0 {
		groups = append(groups, group)
	}
	parts := make([]generatedPart, 0, len(groups))
	for i, group := range groups {
		used := map[string]bool{}
		for _, decl := range group {
			ast.Inspect(decl, func(node ast.Node) bool {
				if selector, ok := node.(*ast.SelectorExpr); ok {
					if ident, ok := selector.X.(*ast.Ident); ok && imports[ident.Name] != "" {
						used[ident.Name] = true
					}
				}
				return true
			})
		}
		var out bytes.Buffer
		out.WriteString("// Code generated by internal/astclonegen; DO NOT EDIT.\npackage ast\n")
		if len(used) != 0 {
			out.WriteString("import (\n")
			for _, spec := range file.Imports {
				path, _ := strconv.Unquote(spec.Path.Value)
				name := filepath.Base(path)
				if spec.Name != nil {
					name = spec.Name.Name
				}
				if used[name] {
					fmt.Fprintf(&out, "%s\n", source[fset.Position(spec.Pos()).Offset:fset.Position(spec.End()).Offset])
				}
			}
			out.WriteString(")\n")
		}
		for _, decl := range group {
			start, end := fset.Position(decl.Pos()).Offset, fset.Position(decl.End()).Offset
			out.Write(source[start:end])
			out.WriteString("\n\n")
		}
		formatted, err := format.Source(out.Bytes())
		if err != nil {
			return nil, err
		}
		if bytes.Count(formatted, []byte("\n")) > 600 {
			return nil, fmt.Errorf("generated part %d exceeds 600 lines", i)
		}
		name := "src/ast/syntax_snapshot_gen.go"
		if i != 0 {
			name = fmt.Sprintf("src/ast/syntax_snapshot_part_%03d_gen.go", i)
		}
		parts = append(parts, generatedPart{name: name, data: formatted})
	}
	if len(parts) == 0 || !strings.Contains(string(parts[0].data), "package ast") {
		return nil, fmt.Errorf("no generated syntax declarations")
	}
	return parts, nil
}
