package main

import (
	"bytes"
	"fmt"
	"go/format"
	"go/importer"
	"go/token"
	"go/types"
	"sort"
)

// Coordinate capture has a separate policy from binding and canonical scans:
// every AST pointer emits Pos(), every concrete lexer.Pos emits its full value,
// maps/arrays are leaves, and all pointer identities share one visitation set.
func generateProofCoordinate() ([]byte, error) {
	fset := token.NewFileSet()
	im := &srcImporter{fset: fset, std: importer.ForCompiler(fset, "source", nil), cache: map[string]*types.Package{}}
	pkg, err := im.Import("elisacore/src/ast")
	if err != nil {
		return nil, err
	}
	name, ok := pkg.Scope().Lookup("Node").(*types.TypeName)
	if !ok {
		return nil, fmt.Errorf("ast.Node not found")
	}
	nodeInterface, ok := types.Unalias(name.Type()).Underlying().(*types.Interface)
	if !ok {
		return nil, fmt.Errorf("ast.Node not an interface")
	}
	nodeInterface.Complete()
	var structs []*types.Named
	for _, name := range pkg.Scope().Names() {
		tn, ok := pkg.Scope().Lookup(name).(*types.TypeName)
		if !ok || tn.IsAlias() || !tn.Exported() {
			continue
		}
		named, ok := tn.Type().(*types.Named)
		if !ok || named.TypeParams().Len() != 0 {
			continue
		}
		if _, ok := named.Underlying().(*types.Struct); ok {
			structs = append(structs, named)
		}
	}
	sort.Slice(structs, func(i, j int) bool { return structs[i].Obj().Name() < structs[j].Obj().Name() })
	var out bytes.Buffer
	out.WriteString("// Code generated by internal/astwalkgen; DO NOT EDIT.\n// Typed equivalent of the complete proof-coordinate capture walk.\n\npackage semantic\nimport(\"reflect\";\"unsafe\";\"elisacore/src/ast\";\"elisacore/src/lexer\")\n")
	out.WriteString("func proofCoordinateASTWalkTyped(root *ast.File,add func(lexer.Pos),seen map[uintptr]bool){proofCoordinateWalkPtr_ast_File(root,add,seen)}\n")
	out.WriteString("func proofCoordinateWalkAny(value any,add func(lexer.Pos),seen map[uintptr]bool)bool{switch node:=value.(type){\n")
	for _, named := range structs {
		fmt.Fprintf(&out, "case *%s:proofCoordinateWalkPtr_%s(node,add,seen);return true\n", qual(named), ident(named))
	}
	out.WriteString("default:return false\n}}\n")
	for _, named := range structs {
		key := ident(named)
		fmt.Fprintf(&out, "func proofCoordinateWalkPtr_%s(p *%s,add func(lexer.Pos),seen map[uintptr]bool){if p==nil{return};key:=uintptr(unsafe.Pointer(p));if seen[key]{return};seen[key]=true\n", key, qual(named))
		if types.Implements(types.NewPointer(named), nodeInterface) {
			out.WriteString("add(p.Pos())\n")
		}
		fmt.Fprintf(&out, "proofCoordinateWalkVal_%s(p,add,seen)}\n", key)
		fmt.Fprintf(&out, "func proofCoordinateWalkVal_%s(p *%s,add func(lexer.Pos),seen map[uintptr]bool){\n", key, qual(named))
		st := named.Underlying().(*types.Struct)
		inaccessible := false
		for i := 0; i < st.NumFields(); i++ {
			if !st.Field(i).Exported() {
				inaccessible = true
			}
		}
		if inaccessible {
			out.WriteString("proofCoordinateWalkReflect(reflect.ValueOf(p).Elem(),add,seen)\n")
		} else {
			for i := 0; i < st.NumFields(); i++ {
				field := st.Field(i)
				if err := emitProofCoordinateValue(&out, "p."+field.Name(), field.Type(), 0); err != nil {
					return nil, fmt.Errorf("%s.%s: %w", named.Obj().Name(), field.Name(), err)
				}
			}
		}
		out.WriteString("}\n")
	}
	return format.Source(out.Bytes())
}

func emitProofCoordinateValue(out *bytes.Buffer, expr string, t types.Type, depth int) error {
	t = types.Unalias(t)
	switch tt := t.(type) {
	case *types.Basic:
		// Scalar values cannot add positions or enter the pointer visit set.
	case *types.Named:
		// A defined pointer type has no methods from its pointed-to type.
		// Unwrapping it could spuriously emit an AST Node.Pos() observation.
		if _, definedPointer := tt.Underlying().(*types.Pointer); definedPointer {
			fmt.Fprintf(out, "proofCoordinateWalkReflect(reflect.ValueOf(%s),add,seen)\n", expr)
			return nil
		}
		if tt.Obj().Pkg() != nil && tt.Obj().Pkg().Path() == "elisacore/src/lexer" && tt.Obj().Name() == "Pos" {
			fmt.Fprintf(out, "add(%s)\n", expr)
			return nil
		}
		if tt.Obj().Pkg() != nil && tt.Obj().Pkg().Path() == "elisacore/src/ast" && tt.Obj().Exported() {
			if _, ok := tt.Underlying().(*types.Struct); ok {
				fmt.Fprintf(out, "proofCoordinateWalkVal_%s(&%s,add,seen)\n", ident(tt), expr)
				return nil
			}
		}
		return emitProofCoordinateValue(out, expr, tt.Underlying(), depth)
	case *types.Pointer:
		if named, ok := types.Unalias(tt.Elem()).(*types.Named); ok && named.Obj().Pkg() != nil && named.Obj().Pkg().Path() == "elisacore/src/ast" && named.Obj().Exported() {
			if _, ok := named.Underlying().(*types.Struct); ok {
				fmt.Fprintf(out, "proofCoordinateWalkPtr_%s(%s,add,seen)\n", ident(named), expr)
				return nil
			}
		}
		// Even scalar pointers enter seen in the original walk; preserve that guard.
		fmt.Fprintf(out, "proofCoordinateWalkReflect(reflect.ValueOf(%s),add,seen)\n", expr)
	case *types.Interface:
		fmt.Fprintf(out, "if %s!=nil {if !proofCoordinateWalkAny(%s,add,seen){proofCoordinateWalkReflect(reflect.ValueOf(%s),add,seen)}}\n", expr, expr, expr)
	case *types.Slice:
		if basic, ok := types.Unalias(tt.Elem()).Underlying().(*types.Basic); ok && basic.Kind() == types.Uint8 {
			return nil
		}
		index := fmt.Sprintf("i%d", depth)
		var body bytes.Buffer
		if err := emitProofCoordinateValue(&body, expr+"["+index+"]", tt.Elem(), depth+1); err != nil {
			return err
		}
		if body.Len() != 0 {
			fmt.Fprintf(out, "for %s:=range %s{\n", index, expr)
			out.Write(body.Bytes())
			out.WriteString("}\n")
		}
	case *types.Struct:
		fmt.Fprintf(out, "proofCoordinateWalkReflect(reflect.ValueOf(&%s).Elem(),add,seen)\n", expr)
	case *types.Array, *types.Map, *types.Signature, *types.Chan:
		// Deliberate leaves in the original capture walk.
	default:
		return fmt.Errorf("unsupported coordinate field type %T", t)
	}
	return nil
}
