package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const generatedPartLimit = 600

var pointerCase = regexp.MustCompile(`(?m)^(\s*case \*ast\.[A-Za-z0-9_]+):\n\s*([A-Za-z0-9_]+\([^\n]*\))(?:\n\s*(return true))?`)

// compactCases keeps a generated type switch intact while placing its simple
// case and call on one line. The Go formatter expands these cases, but keeping
// the switch intact preserves the compiler's existing type-dispatch behavior.
func compactCases(source string) string {
	return pointerCase.ReplaceAllStringFunc(source, func(match string) string {
		parts := pointerCase.FindStringSubmatch(match)
		line := parts[1] + ": " + parts[2]
		if parts[3] != "" {
			line += "; " + parts[3]
		}
		return line
	})
}

type generatedDecl struct {
	label   string
	text    string
	imports map[string]bool
}

func renderGeneratedPart(pkg string, decls []generatedDecl) []byte {
	imports := map[string]string{
		"ast": "elisacore/src/ast", "lexer": "elisacore/src/lexer",
		"reflect": "reflect", "unsafe": "unsafe",
	}
	used := make(map[string]bool)
	for _, decl := range decls {
		for name := range decl.imports {
			used[name] = true
		}
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by internal/astwalkgen; DO NOT EDIT.\n\npackage %s\n\n", pkg)
	if len(used) != 0 {
		out.WriteString("import (\n")
		var paths []string
		for name := range used {
			paths = append(paths, imports[name])
		}
		sort.Strings(paths)
		for _, path := range paths {
			fmt.Fprintf(&out, "\t%q\n", path)
		}
		out.WriteString(")\n\n")
	}
	for _, decl := range decls {
		out.WriteString(decl.text)
		out.WriteString("\n\n")
	}
	return out.Bytes()
}

// generatedParts partitions whole declarations, so helpers remain independently
// readable and the generated type switches keep their original dispatch logic.
func generatedParts(m walkMode, source []byte) (map[string][]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, m.File, source, 0)
	if err != nil {
		return nil, err
	}
	var declarations []generatedDecl
	for _, decl := range file.Decls {
		if g, ok := decl.(*ast.GenDecl); ok && g.Tok == token.IMPORT {
			continue
		}
		start, end := fset.Position(decl.Pos()).Offset, fset.Position(decl.End()).Offset
		text := compactCases(string(source[start:end]))
		used := make(map[string]bool)
		ast.Inspect(decl, func(node ast.Node) bool {
			if sel, ok := node.(*ast.SelectorExpr); ok {
				if id, ok := sel.X.(*ast.Ident); ok {
					switch id.Name {
					case "ast", "lexer", "reflect", "unsafe":
						used[id.Name] = true
					}
				}
			}
			return true
		})
		label := "declaration"
		if function, ok := decl.(*ast.FuncDecl); ok {
			label = function.Name.Name
			if function.Type.Params != nil && len(function.Type.Params.List) > 0 {
				var typ bytes.Buffer
				if err := format.Node(&typ, fset, function.Type.Params.List[0].Type); err != nil {
					return nil, err
				}
				label = typ.String()
			}
		}
		label = strings.NewReplacer("*", "ptr_", "[]", "slice_", ".", "_", "[", "_", "]", "_", " ", "_").Replace(label)
		declarations = append(declarations, generatedDecl{label: strings.ToLower(label), text: text, imports: used})
	}
	parts := make(map[string][]byte)
	stem := strings.TrimSuffix(m.File, "_gen.go")
	var current []generatedDecl
	index := 0
	flush := func() {
		name := m.File
		if index > 0 {
			name = fmt.Sprintf("%s_range_%s_through_%s_gen.go", stem, current[0].label, current[len(current)-1].label)
		}
		if _, duplicate := parts[name]; duplicate {
			panic("duplicate generated declaration range: " + name)
		}
		parts[name] = renderGeneratedPart(file.Name.Name, current)
		index++
		current = nil
	}
	for _, decl := range declarations {
		candidate := append(append([]generatedDecl(nil), current...), decl)
		if bytes.Count(renderGeneratedPart(file.Name.Name, candidate), []byte("\n")) > generatedPartLimit && len(current) > 0 {
			flush()
			candidate = []generatedDecl{decl}
		}
		if bytes.Count(renderGeneratedPart(file.Name.Name, candidate), []byte("\n")) > generatedPartLimit {
			return nil, fmt.Errorf("%s has a declaration exceeding %d lines", m.File, generatedPartLimit)
		}
		current = candidate
	}
	if len(current) > 0 {
		flush()
	}
	return parts, nil
}

func writeGeneratedParts(m walkMode, source []byte) error {
	parts, err := generatedParts(m, source)
	if err != nil {
		return err
	}
	stem := strings.TrimSuffix(m.File, "_gen.go")
	var old []string
	for _, pattern := range []string{stem + "_part_*_gen.go", stem + "_range_*_gen.go"} {
		matches, err := filepath.Glob(pattern)
		if err != nil {
			return err
		}
		old = append(old, matches...)
	}
	for _, path := range old {
		if _, exists := parts[path]; exists {
			continue
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.HasPrefix(data, []byte("// Code generated by internal/astwalkgen; DO NOT EDIT.")) {
			return fmt.Errorf("refusing to remove non-generated file %s", path)
		}
		if err := os.Remove(path); err != nil {
			return err
		}
	}
	for path, data := range parts {
		if err := os.WriteFile(path, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}
