// Command gen regenerates the frontend IR schema root list.
//
//	go run ./src/frontendir/gen
//
// It scans src/ast for exported struct types and writes schema_roots_gen.go.
// TestSchemaRootsMatchSource fails when the two disagree, so running this is the
// fix for that failure rather than something to remember.
package main

import (
	"fmt"
	"os"
	"strings"

	"elisacore/src/frontendir"
)

func main() {
	names, err := frontendir.ScanASTStructNames("src/ast")
	if err != nil {
		fmt.Fprintln(os.Stderr, "scan:", err)
		os.Exit(1)
	}
	var b strings.Builder
	b.WriteString("// Code generated by `go run ./src/frontendir/gen`. DO NOT EDIT.\n\n")
	b.WriteString("package frontendir\n\nimport (\n\t\"reflect\"\n\n\t\"elisacore/src/ast\"\n)\n\n")
	b.WriteString("// schemaRootTypes is every exported struct type in package ast. It is the\n")
	b.WriteString("// root set for schema derivation: interfaces cannot be enumerated by\n")
	b.WriteString("// reflection, so the concrete node types have to be named somewhere.\n")
	b.WriteString("var schemaRootTypes = []reflect.Type{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\treflect.TypeOf(ast.%s{}),\n", name)
	}
	b.WriteString("}\n")
	if err := os.WriteFile("src/frontendir/schema_roots_gen.go", []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "write:", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %d root types\n", len(names))

	// The registry is regenerated against the roots compiled into THIS binary, so
	// a run that adds root types has to be followed by a second run to number
	// them. The command reports when that is the case rather than leaving it to
	// be discovered by a failing test.
	registry, err := frontendir.RegenerateRegistry()
	if err != nil {
		fmt.Fprintln(os.Stderr, "registry:", err)
		os.Exit(1)
	}
	previous, _ := os.ReadFile("src/frontendir/schema_registry.txt")
	if err := os.WriteFile("src/frontendir/schema_registry.txt", []byte(registry), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "write registry:", err)
		os.Exit(1)
	}
	if string(previous) == registry {
		fmt.Println("schema registry unchanged")
	} else {
		fmt.Println("schema registry updated — re-run to pick up any newly generated roots")
	}
}
