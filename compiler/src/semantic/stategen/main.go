// Command stategen lists the local named types available to the semantic-state
// decoder. Unknown dynamic interface types are rejected rather than guessed.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	for {
		if _, err := os.Stat("go.mod"); err == nil {
			break
		}
		cwd, err := os.Getwd()
		must(err)
		parent := filepath.Dir(cwd)
		if parent == cwd {
			panic("compiler module root not found")
		}
		must(os.Chdir(parent))
	}

	var names []string
	for _, pkg := range []string{"semantic", "ast", "lexer", "easm"} {
		files, err := filepath.Glob(filepath.Join("src", pkg, "*.go"))
		must(err)
		for _, file := range files {
			if strings.HasSuffix(file, "_test.go") || strings.HasPrefix(filepath.Base(file), "state_registry_gen") {
				continue
			}
			f, err := parser.ParseFile(token.NewFileSet(), file, nil, 0)
			must(err)
			for _, decl := range f.Decls {
				g, ok := decl.(*ast.GenDecl)
				if !ok || g.Tok != token.TYPE {
					continue
				}
				for _, spec := range g.Specs {
					t := spec.(*ast.TypeSpec)
					if t.TypeParams != nil {
						continue
					}
					name := t.Name.Name
					if pkg != "semantic" {
						if !ast.IsExported(name) {
							continue
						}
						name = pkg + "." + name
					}
					names = append(names, name)
				}
			}
		}
	}
	sort.Strings(names)
	unique := names[:0]
	for _, name := range names {
		if len(unique) == 0 || unique[len(unique)-1] != name {
			unique = append(unique, name)
		}
	}
	const chunkSize = 400
	chunks := (len(unique) + chunkSize - 1) / chunkSize
	var index bytes.Buffer
	index.WriteString("// Code generated by go run ./src/semantic/stategen; DO NOT EDIT.\npackage semantic\nimport \"reflect\"\nfunc semanticStateTypes() []reflect.Type {\nvar types []reflect.Type\n")
	for part := 0; part < chunks; part++ {
		fmt.Fprintf(&index, "types = append(types, semanticStateTypesPart%d()...)\n", part)
		start, end := part*chunkSize, min((part+1)*chunkSize, len(unique))
		items := unique[start:end]
		var out bytes.Buffer
		out.WriteString("// Code generated by go run ./src/semantic/stategen; DO NOT EDIT.\npackage semantic\nimport (\"reflect\"\n")
		for _, pkg := range []string{"ast", "lexer", "easm"} {
			for _, name := range items {
				if strings.HasPrefix(name, pkg+".") {
					fmt.Fprintf(&out, "\"elisacore/src/%s\"\n", pkg)
					break
				}
			}
		}
		fmt.Fprintf(&out, ")\nfunc semanticStateTypesPart%d() []reflect.Type { return []reflect.Type{\n", part)
		for _, name := range items {
			fmt.Fprintf(&out, "reflect.TypeFor[%s](),\n", name)
		}
		out.WriteString("}}\n")
		formatted, err := format.Source(out.Bytes())
		must(err)
		must(os.WriteFile(fmt.Sprintf("src/semantic/state_registry_gen_part%d.go", part), formatted, 0644))
	}
	index.WriteString("return types\n}\n")
	formatted, err := format.Source(index.Bytes())
	must(err)
	must(os.WriteFile("src/semantic/state_registry_gen.go", formatted, 0644))
	stale, err := filepath.Glob("src/semantic/state_registry_gen_part*.go")
	must(err)
	for _, file := range stale {
		var part int
		if _, err := fmt.Sscanf(filepath.Base(file), "state_registry_gen_part%d.go", &part); err == nil && part >= chunks {
			must(os.Remove(file))
		}
	}
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
