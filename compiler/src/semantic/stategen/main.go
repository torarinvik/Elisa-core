// Command stategen lists the local named types available to the semantic-state
// decoder. Unknown dynamic interface types are rejected rather than guessed.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	for {
		if _, err := os.Stat("go.mod"); err == nil {
			break
		}
		cwd, err := os.Getwd()
		must(err)
		parent := filepath.Dir(cwd)
		if parent == cwd {
			panic("compiler module root not found")
		}
		must(os.Chdir(parent))
	}

	var names []string
	for _, pkg := range []string{"semantic", "ast", "lexer", "easm"} {
		files, err := filepath.Glob(filepath.Join("src", pkg, "*.go"))
		must(err)
		for _, file := range files {
			if strings.HasSuffix(file, "_test.go") || strings.HasSuffix(file, "state_registry_gen.go") {
				continue
			}
			f, err := parser.ParseFile(token.NewFileSet(), file, nil, 0)
			must(err)
			for _, decl := range f.Decls {
				g, ok := decl.(*ast.GenDecl)
				if !ok || g.Tok != token.TYPE {
					continue
				}
				for _, spec := range g.Specs {
					t := spec.(*ast.TypeSpec)
					if t.TypeParams != nil {
						continue
					}
					name := t.Name.Name
					if pkg != "semantic" {
						if !ast.IsExported(name) {
							continue
						}
						name = pkg + "." + name
					}
					names = append(names, name)
				}
			}
		}
	}
	sort.Strings(names)
	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./src/semantic/stategen; DO NOT EDIT.\npackage semantic\nimport(\"reflect\";\"elisacore/src/ast\";\"elisacore/src/lexer\";\"elisacore/src/easm\")\nfunc semanticStateTypes()[]reflect.Type{return []reflect.Type{\n")
	previous := ""
	for _, name := range names {
		if name == previous {
			continue
		}
		fmt.Fprintf(&out, "reflect.TypeFor[%s](),\n", name)
		previous = name
	}
	out.WriteString("}}\n")
	formatted, err := format.Source(out.Bytes())
	must(err)
	must(os.WriteFile("src/semantic/state_registry_gen.go", formatted, 0644))
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
