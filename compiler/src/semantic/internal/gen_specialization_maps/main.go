// Command gen_specialization_maps emits typed outer-map copies. Resource policy
// stays in the generated runtime guard, never in a hand-maintained type list.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func generate(source []byte) ([]byte, error) {
	f, err := parser.ParseFile(token.NewFileSet(), "analyzer.go", source, 0)
	if err != nil {
		return nil, err
	}
	var fields []string
	for _, decl := range f.Decls {
		group, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range group.Specs {
			typ, ok := spec.(*ast.TypeSpec)
			if !ok || typ.Name.Name != "Analyzer" {
				continue
			}
			body, ok := typ.Type.(*ast.StructType)
			if !ok {
				return nil, fmt.Errorf("Analyzer must be a struct")
			}
			for _, field := range body.Fields.List {
				if _, ok := field.Type.(*ast.MapType); !ok {
					continue // Unknown/named resource shapes retain reflective fallback.
				}
				for _, name := range field.Names {
					if name.Name != "exprTypes" && name.Name != "exprFacts" && name.Name != "iterBinderElementStates" && name.Name != "optimizationSymbolIDs" && name.Name != "storeScanBinderTypes" && name.Name != "storeScanParamFactsCache" && name.Name != "functionAnalyses" {
						fields = append(fields, name.Name)
					}
				}
			}
		}
	}
	if len(fields) == 0 {
		return nil, fmt.Errorf("no direct Analyzer maps found")
	}
	sort.Strings(fields)
	var out bytes.Buffer
	fmt.Fprint(&out, "// Code generated by gen_specialization_maps; DO NOT EDIT.\npackage semantic\n\nimport (\n\"maps\"\n\"reflect\"\n)\n\n")
	fmt.Fprint(&out, "var specializationOpaqueMapFields = [...]string{\n")
	for _, field := range fields {
		fmt.Fprintf(&out, "%q,\n", field)
	}
	fmt.Fprint(&out, "}\n\n")
	fmt.Fprint(&out, "// cloneSpecializationOpaqueMap preserves deepCloneValue's opaque value policy.\n// Policy-specific exclusions must be handled by the caller before this fallback.\nfunc cloneSpecializationOpaqueMap(dst, src *Analyzer, name string, field reflect.Value) bool {\n")
	fmt.Fprint(&out, "if field.Kind() != reflect.Map || typeHoldsMapInline(field.Type().Elem()) { return false }\nswitch name {\n")
	for _, field := range fields {
		fmt.Fprintf(&out, "case %q:\ndst.%s = maps.Clone(src.%s)\nreturn true\n", field, field, field)
	}
	fmt.Fprint(&out, "default:\nreturn false\n}\n}\n")
	return format.Source(out.Bytes())
}

// splitGenerated keeps the resource guard central and distributes typed copies
// in bounded files. Parts retain sorted switch cases and fail closed on misses.
func splitGenerated(generated []byte) ([][]byte, error) {
	text := string(generated)
	marker := "\tswitch name {\n"
	pos := strings.Index(text, marker)
	if pos < 0 {
		return nil, fmt.Errorf("missing generated switch")
	}
	prefix := strings.Replace(text[:pos], "\t\"maps\"\n", "", 1)
	casesText := text[pos+len(marker):]
	end := strings.LastIndex(casesText, "\tdefault:\n")
	if end < 0 {
		return nil, fmt.Errorf("missing generated default")
	}
	cases := strings.Split(strings.TrimSuffix(casesText[:end], "\n"), "\n\tcase ")
	if len(cases) == 0 || !strings.HasPrefix(cases[0], "\tcase ") {
		return nil, fmt.Errorf("missing generated cases")
	}
	cases[0] = strings.TrimPrefix(cases[0], "\tcase ")
	const chunkSize = 100
	count := (len(cases) + chunkSize - 1) / chunkSize
	var wrapper strings.Builder
	wrapper.WriteString(prefix)
	for i := 0; i < count; i++ {
		fmt.Fprintf(&wrapper, "if cloneSpecializationOpaqueMapPart%d(dst, src, name) { return true }\n", i)
	}
	wrapper.WriteString("return false\n}\n")
	first, err := format.Source([]byte(wrapper.String()))
	if err != nil {
		return nil, err
	}
	files := [][]byte{first}
	for i := 0; i < count; i++ {
		var part strings.Builder
		fmt.Fprintf(&part, "// Code generated by gen_specialization_maps; DO NOT EDIT.\npackage semantic\nimport \"maps\"\nfunc cloneSpecializationOpaqueMapPart%d(dst, src *Analyzer, name string) bool {\nswitch name {\n", i)
		for _, c := range cases[i*chunkSize : min((i+1)*chunkSize, len(cases))] {
			part.WriteString("case " + c + "\n")
		}
		part.WriteString("default: return false\n}\n}\n")
		formatted, err := format.Source([]byte(part.String()))
		if err != nil {
			return nil, err
		}
		files = append(files, formatted)
	}
	return files, nil
}

func main() {
	input := flag.String("input", "analyzer.go", "Analyzer source")
	output := flag.String("output", "specialization_maps_generated.go", "generated file")
	flag.Parse()
	source, err := os.ReadFile(*input)
	if err != nil {
		panic(err)
	}
	generated, err := generate(source)
	if err != nil {
		panic(err)
	}
	files, err := splitGenerated(generated)
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(*output, files[0], 0644); err != nil {
		panic(err)
	}
	stem := strings.TrimSuffix(*output, ".go")
	wanted := make(map[string]bool)
	for _, file := range files[1:] {
		cases := strings.Split(string(file), "\n\tcase \"")
		if len(cases) < 2 {
			panic("generated specialization clone has no fields")
		}
		first, _, ok := strings.Cut(cases[1], "\"")
		if !ok {
			panic("invalid first generated field")
		}
		last, _, ok := strings.Cut(cases[len(cases)-1], "\"")
		if !ok {
			panic("invalid last generated field")
		}
		name := fmt.Sprintf("%s_fields_%s_through_%s.go", stem, strings.ToLower(first), strings.ToLower(last))
		if wanted[name] {
			panic("duplicate specialization field range: " + name)
		}
		wanted[name] = true
		if err := os.WriteFile(name, file, 0644); err != nil {
			panic(err)
		}
	}
	for _, pattern := range []string{stem + "_part*.go", stem + "_fields_*_through_*.go"} {
		stale, err := filepath.Glob(pattern)
		if err != nil {
			panic(err)
		}
		for _, file := range stale {
			if !wanted[file] {
				data, err := os.ReadFile(file)
				if err != nil || !bytes.HasPrefix(data, []byte("// Code generated by gen_specialization_maps; DO NOT EDIT.")) {
					panic("refusing to remove non-generated specialization clone: " + file)
				}
				if err := os.Remove(file); err != nil {
					panic(err)
				}
			}
		}
	}
}
