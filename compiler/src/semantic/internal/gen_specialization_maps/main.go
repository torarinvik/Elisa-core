// Command gen_specialization_maps emits typed outer-map copies. Resource policy
// stays in the generated runtime guard, never in a hand-maintained type list.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
)

func generate(source []byte) ([]byte, error) {
	f, err := parser.ParseFile(token.NewFileSet(), "analyzer.go", source, 0)
	if err != nil {
		return nil, err
	}
	var fields []string
	for _, decl := range f.Decls {
		group, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range group.Specs {
			typ, ok := spec.(*ast.TypeSpec)
			if !ok || typ.Name.Name != "Analyzer" {
				continue
			}
			body, ok := typ.Type.(*ast.StructType)
			if !ok {
				return nil, fmt.Errorf("Analyzer must be a struct")
			}
			for _, field := range body.Fields.List {
				if _, ok := field.Type.(*ast.MapType); !ok {
					continue // Unknown/named resource shapes retain reflective fallback.
				}
				for _, name := range field.Names {
					if name.Name != "exprTypes" && name.Name != "exprFacts" && name.Name != "functionAnalyses" {
						fields = append(fields, name.Name)
					}
				}
			}
		}
	}
	if len(fields) == 0 {
		return nil, fmt.Errorf("no direct Analyzer maps found")
	}
	sort.Strings(fields)
	var out bytes.Buffer
	fmt.Fprint(&out, "// Code generated by gen_specialization_maps; DO NOT EDIT.\npackage semantic\n\nimport (\n\"maps\"\n\"reflect\"\n)\n\n")
	fmt.Fprint(&out, "var specializationOpaqueMapFields = [...]string{\n")
	for _, field := range fields {
		fmt.Fprintf(&out, "%q,\n", field)
	}
	fmt.Fprint(&out, "}\n\n")
	fmt.Fprint(&out, "// cloneSpecializationOpaqueMap preserves deepCloneValue's opaque value policy.\n// Policy-specific exclusions must be handled by the caller before this fallback.\nfunc cloneSpecializationOpaqueMap(dst, src *Analyzer, name string, field reflect.Value) bool {\n")
	fmt.Fprint(&out, "if field.Kind() != reflect.Map || typeHoldsMapInline(field.Type().Elem()) { return false }\nswitch name {\n")
	for _, field := range fields {
		fmt.Fprintf(&out, "case %q:\ndst.%s = maps.Clone(src.%s)\nreturn true\n", field, field, field)
	}
	fmt.Fprint(&out, "default:\nreturn false\n}\n}\n")
	return format.Source(out.Bytes())
}

func main() {
	input := flag.String("input", "analyzer.go", "Analyzer source")
	output := flag.String("output", "specialization_maps_generated.go", "generated file")
	flag.Parse()
	source, err := os.ReadFile(*input)
	if err != nil {
		panic(err)
	}
	generated, err := generate(source)
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(*output, generated, 0644); err != nil {
		panic(err)
	}
}
