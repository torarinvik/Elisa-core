#!/usr/bin/env python3
"""Generate diagnostic Result read wrappers from the sparse accessor schema.

The reviewed schema remains the sole table/type inventory. This generator adds
no reuse authority. --check compares exact formatted output without rewriting.
"""
import argparse
import json
from pathlib import Path
import subprocess
import sys


def generate(directory: Path) -> bytes:
    fields = json.loads((directory / "generate_specialization_accessors.schema.json").read_text())["fields"]
    lines = ['// Code generated by scripts/generate_codegen_read_view.py; DO NOT EDIT.',
             'package semantic', 'import "elisacore/src/ast"']
    names = set()
    for field in fields:
        if "analyzer" not in field:
            continue
        name, typ = field['name'], field['type']
        if name in names or not typ.startswith('map['):
            raise ValueError('invalid sparse map policy: ' + name)
        names.add(name)
        close = typ.index(']')
        key, value = typ[4:close], typ[close + 1:]
        for operation in ('Lookup', 'Value'):
            signature = f'({value},bool)' if operation == 'Lookup' else value
            returned = 'value,present' if operation == 'Lookup' else 'value'
            lines.append(f'''func (v CodegenReadView) {operation}{name}(key {key}) {signature} {{
 value,present:=v.Result.Lookup{name}(key)
 if v.Observe!=nil {{v.Observe(CodegenFactRead{{Result:v.Result,Table:"{name}",Operation:"{operation.lower()}",Key:key,Value:value,Present:present}})}}
 return {returned}
}}''')
        lines.append(f'''func (v CodegenReadView) Range{name}(yield func({key},{value})bool) {{
 if v.Observe==nil {{v.Result.Range{name}(yield);return}}
 complete:=false
 defer func(){{v.Observe(CodegenFactRead{{Result:v.Result,Table:"{name}",Operation:"range-end",Complete:complete}})}}()
 if yield==nil {{return}}
 stopped:=false
 v.Result.Range{name}(func(key {key},value {value})bool{{
  v.Observe(CodegenFactRead{{Result:v.Result,Table:"{name}",Operation:"range-item",Key:key,Value:value,Present:true}})
  if !yield(key,value) {{stopped=true;return false}}
  return true
 }})
 complete=!stopped
}}
func (v CodegenReadView) {name}Len() int {{
 count:=v.Result.{name}Len()
 if v.Observe!=nil {{v.Observe(CodegenFactRead{{Result:v.Result,Table:"{name}",Operation:"len",Value:count,Present:true}})}}
 return count
}}''')
    # Some reviewed values include EASM payloads; import only when schema needs it.
    if any('easm.' in f['type'] for f in fields if 'analyzer' in f):
        lines[2] = 'import ("elisacore/src/ast";"elisacore/src/easm")'
    return subprocess.run(['gofmt'], input='\n\n'.join(lines).encode(), stdout=subprocess.PIPE, check=True).stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    directory = Path(__file__).resolve().parent
    target = directory.parent / 'src/semantic/codegen_read_view_gen.go'
    generated = generate(directory)
    if args.check:
        if not target.exists() or target.read_bytes() != generated:
            print('diagnostic codegen read view is stale', file=sys.stderr)
            return 1
    else:
        target.write_bytes(generated)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
