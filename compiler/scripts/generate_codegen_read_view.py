#!/usr/bin/env python3
"""Generate diagnostic Result read wrappers from the sparse accessor schema.

The reviewed schema remains the sole table/type inventory. This generator adds
no reuse authority. --check compares exact formatted output without rewriting.
"""
import argparse
import json
from pathlib import Path
import subprocess
import sys

from specialization_field_groups import FIELD_GROUPS


def generate(directory: Path) -> dict[str, bytes]:
    fields = json.loads((directory / "generate_specialization_accessors.schema.json").read_text())["fields"]
    categories = FIELD_GROUPS
    parts = {category: [] for category in categories}
    names = set()
    for field in fields:
        if "analyzer" not in field:
            continue
        lines = []
        name, typ = field['name'], field['type']
        if name in names or not typ.startswith('map['):
            raise ValueError('invalid sparse map policy: ' + name)
        names.add(name)
        close = typ.index(']')
        key, value = typ[4:close], typ[close + 1:]
        for operation in ('Lookup', 'Value'):
            signature = f'({value},bool)' if operation == 'Lookup' else value
            returned = 'value,present' if operation == 'Lookup' else 'value'
            lines.append(f'''func (v CodegenReadView) {operation}{name}(key {key}) {signature} {{
 value,present:=v.Result.Lookup{name}(key)
 if v.Observe!=nil {{v.Observe(CodegenFactRead{{Result:v.Result,Table:"{name}",Operation:"{operation.lower()}",Key:key,Value:value,Present:present}})}}
 return {returned}
}}''')
        lines.append(f'''func (v CodegenReadView) Range{name}(yield func({key},{value})bool) {{
 if v.Observe==nil {{v.Result.Range{name}(yield);return}}
 complete:=false
 defer func(){{v.Observe(CodegenFactRead{{Result:v.Result,Table:"{name}",Operation:"range-end",Complete:complete}})}}()
 if yield==nil {{return}}
 stopped:=false
 v.Result.Range{name}(func(key {key},value {value})bool{{
  v.Observe(CodegenFactRead{{Result:v.Result,Table:"{name}",Operation:"range-item",Key:key,Value:value,Present:true}})
  if !yield(key,value) {{stopped=true;return false}}
  return true
 }})
 complete=!stopped
}}
func (v CodegenReadView) {name}Len() int {{
 count:=v.Result.{name}Len()
 if v.Observe!=nil {{v.Observe(CodegenFactRead{{Result:v.Result,Table:"{name}",Operation:"len",Value:count,Present:true}})}}
 return count
}}''')
        lines.append(f'''// HasOwn{name}Map observes physical presence on this Result only.
func (v CodegenReadView) HasOwn{name}Map() bool {{
 present:=v.Result!=nil && v.Result.{name}!=nil
 if v.Observe!=nil {{v.Observe(CodegenFactRead{{Result:v.Result,Table:"{name}",Operation:"own-map-presence",Value:present,Present:present}})}}
 return present
}}
// Own{name}Map returns the original current-Result map without logical fallback.
// Only the diagnostic event owns a shallow membership snapshot; payloads remain opaque.
func (v CodegenReadView) Own{name}Map() {typ} {{
 var own {typ}
 if v.Result!=nil {{own=v.Result.{name}}}
 if v.Observe!=nil {{v.Observe(CodegenFactRead{{Result:v.Result,Table:"{name}",Operation:"own-map",Value:maps.Clone(own),Present:own!=nil}})}}
 return own
}}''')
        matches = [category for category, members in categories.items() if name in members]
        if len(matches) != 1:
            raise ValueError('read view field needs exactly one responsibility: ' + name)
        parts[matches[0]].append("\n\n".join(lines))
    if names != set().union(*categories.values()):
        raise ValueError('read view responsibility groups do not match the schema')
    outputs = {}
    for category, chunks in parts.items():
        chunk = "\n\n".join(chunks)
        imports = ['"maps"']
        for marker, path in (("ast.", "elisacore/src/ast"), ("easm.", "elisacore/src/easm")):
            if marker in chunk:
                imports.append(f'"{path}"')
        source = ('// Code generated by scripts/generate_codegen_read_view.py; DO NOT EDIT.\n'
                  + 'package semantic\nimport (' + ';'.join(imports) + ')\n' + chunk)
        data = subprocess.run(['gofmt'], input=source.encode(), stdout=subprocess.PIPE, check=True).stdout
        if len(data.splitlines()) > 600:
            raise ValueError('generated read view part exceeds 600 lines')
        name = f'codegen_read_view_{category}_gen.go'
        outputs[name] = data
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    directory = Path(__file__).resolve().parent
    target_dir = directory.parent / 'src/semantic'
    generated = generate(directory)
    existing = {p.name for p in target_dir.glob('codegen_read_view*_gen.go')}
    if args.check:
        if existing != set(generated) or any((target_dir / name).read_bytes() != data for name, data in generated.items()):
            print('diagnostic codegen read view is stale', file=sys.stderr)
            return 1
    else:
        for name in existing - set(generated):
            (target_dir / name).unlink()
        for name, data in generated.items():
            (target_dir / name).write_bytes(data)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
