#!/usr/bin/env python3
"""Generate typed sparse fact views from an explicitly reviewed Result policy.

Adding a Result field does not auto-admit it: update the schema and its ownership
policy deliberately. Runtime schema validation and backend consumer tests reject
unhandled fields/read paths. --check verifies the committed generated source.
"""
import argparse
import json
from pathlib import Path
import subprocess
import sys


def generate(directory: Path) -> bytes:
    fields = json.loads((directory / "generate_specialization_accessors.schema.json").read_text())["fields"]
    template = (directory / "specialization_accessors.tmpl").read_text()
    names = [field["name"] for field in fields]
    if len(names) != len(set(names)):
        raise ValueError("duplicate Result policy")
    node_maps = [field for field in fields if "analyzer" in field]
    lines = ["// Code generated by scripts/generate_specialization_accessors.py; DO NOT EDIT.\n",
             "package semantic\n", 'import ("reflect"; "elisacore/src/ast"; "elisacore/src/easm")\n',
             "type sparseSpecializationMap struct {result,analyzer string}\n",
             "var sparseSpecializationMaps=[]sparseSpecializationMap{\n"]
    for field in node_maps:
        lines.append('{"' + field["name"] + '","' + field["analyzer"] + '"},\n')
    lines.append("}\nvar sparseSpecializationSchema=map[string]reflect.Type{\n")
    for field in fields:
        lines.append('"' + field["name"] + '":reflect.TypeFor[' + field["type"] + '](),\n')
    lines.append("}\n")
    for field in node_maps:
        kind = field["type"]
        if not kind.startswith("map["):
            raise ValueError("node policy is not a map: " + field["name"])
        close = kind.index("]")
        key, value = kind[4:close], kind[close + 1:]
        body = template.replace("@@NAME@@", field["name"]).replace("@@KEY@@", key).replace("@@VALUE@@", value)
        special = field["name"] == "IndexBoundsProven"
        lookup_mask = "if r.specializationProofMask[key]{return zero,false}" if special else ""
        range_mask = "if r.specializationProofMask[key]{return true}" if special else ""
        body = body.replace("@@LOOKUP_MASK@@", lookup_mask).replace("@@RANGE_MASK@@", range_mask)
        if "@@" in body:
            raise ValueError("unexpanded accessor policy token")
        lines.append(body)
    return subprocess.run(["gofmt"], input="\n".join(lines).encode(), stdout=subprocess.PIPE, check=True).stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    directory = Path(__file__).resolve().parent
    target = directory.parent / "src/semantic/specialization_accessors_gen.go"
    data = generate(directory)
    if args.check:
        if not target.exists() or target.read_bytes() != data:
            print("sparse specialization accessors are stale", file=sys.stderr)
            return 1
    else:
        target.write_bytes(data)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
